import { describe, it, expect } from 'vitest';
import { parse as yamlParse } from 'yaml';
import {
  buildComposeBundle,
  buildDeployScript,
  buildEnvFile,
  buildReadme,
  getDeployTargets,
  normalizeEnvKey,
  stackSlug,
} from '../handoff';
import type { PersistedStack } from '@/lib/stack-persistence';
import type { Service } from '@/types/service';
import type { StackService } from '@/types/stack';

const postgresService: Service = {
  id: 1,
  name: 'PostgreSQL',
  slug: 'postgresql',
  description: 'PostgreSQL database',
  dockerImage: 'postgres:18-alpine',
  version: '18',
  category: { id: 1, name: 'Databases', slug: 'databases' },
  ports: [5432],
  environmentVariables: {},
  env: [
    { name: 'POSTGRES_PASSWORD', description: 'Superuser password', required: true, secret: true },
    { name: 'POSTGRES_USER', description: 'Superuser name', required: false, secret: false, default: 'postgres' },
  ],
  volumes: [{ containerPath: '/var/lib/postgresql/data', description: 'Data dir', named: true }],
};

function buildStack(): PersistedStack {
  const services: StackService[] = [
    {
      id: 'ss-pg',
      serviceId: postgresService.id,
      order: 1,
      service: postgresService,
      configuration: {
        environmentVariables: {},
        portMappings: [{ containerPort: 5432, hostPort: 5432 }],
        volumeMounts: [],
        dependsOn: [],
      },
    },
  ];
  return { name: 'db stack', description: '', isPublic: false, services };
}

describe('buildComposeBundle', () => {
  it('returns compose YAML, a reference .env, and the generated secrets', () => {
    const { composeYaml, envFile, secrets, deployScript } = buildComposeBundle(buildStack());

    // The bundle also ships the key-sovereign deploy.sh.
    expect(deployScript).toContain('#!/usr/bin/env sh');
    expect(deployScript).toContain('PROJECT="bms-db-stack"');
    expect(deployScript).toContain('docker compose -p $PROJECT up -d');

    // Compose is present and parseable, with the generated password inlined.
    const doc = yamlParse(composeYaml);
    const pgPassword = doc.services.postgresql.environment.POSTGRES_PASSWORD;
    expect(typeof pgPassword).toBe('string');
    expect(pgPassword.length).toBeGreaterThan(16);

    // The secret is returned to the caller under the slug.ENV key.
    expect(secrets['postgresql.POSTGRES_PASSWORD']).toBe(pgPassword);

    // The .env mirrors the same secret value under a normalized key.
    expect(envFile).toContain(`POSTGRESQL_POSTGRES_PASSWORD=${pgPassword}`);
    // .env value equals the value inlined in the compose (artifacts agree).
    expect(envFile).toContain(pgPassword);
  });
});

describe('buildEnvFile', () => {
  it('normalizes keys, uppercases, and keeps a header + trailing newline', () => {
    const env = buildEnvFile({ 'postgresql.POSTGRES_PASSWORD': 'sekret', 'redis.REDIS-PASS': 'pw2' });
    expect(env).toContain('POSTGRESQL_POSTGRES_PASSWORD=sekret');
    expect(env).toContain('REDIS_REDIS_PASS=pw2');
    expect(env.startsWith('#')).toBe(true);
    expect(env.endsWith('\n')).toBe(true);
  });

  it('returns just the header for a stack with no secrets', () => {
    const env = buildEnvFile({});
    expect(env).toContain('# Generated by Stapelwerk');
    expect(env).not.toMatch(/^[A-Z].*=/m);
  });
});

describe('normalizeEnvKey', () => {
  it('uppercases and replaces non-word characters with underscores', () => {
    expect(normalizeEnvKey('postgresql.POSTGRES_PASSWORD')).toBe('POSTGRESQL_POSTGRES_PASSWORD');
    expect(normalizeEnvKey('my-svc.some-key')).toBe('MY_SVC_SOME_KEY');
  });
});

describe('getDeployTargets', () => {
  it('provides ordered instructions for every handoff target', () => {
    const targets = getDeployTargets();
    const ids = targets.map(t => t.id);
    expect(ids).toEqual(
      expect.arrayContaining(['portainer', 'coolify', 'dokploy', 'openship', 'docker-compose']),
    );

    for (const target of targets) {
      expect(target.title).toBeTruthy();
      expect(target.steps.length).toBeGreaterThan(0);
      expect(target.steps.every(s => typeof s.title === 'string' && s.title.length > 0)).toBe(true);
      expect(['compose', 'compose+env']).toContain(target.artifact);
    }

    // Plain docker compose is the one that also needs the .env alongside it.
    const plain = targets.find(t => t.id === 'docker-compose');
    expect(plain?.artifact).toBe('compose+env');
    expect(plain?.steps.some(s => `${s.title} ${s.detail ?? ''}`.includes('docker compose up -d'))).toBe(true);

    // Panel targets reference their web editor flow.
    expect(targets.find(t => t.id === 'portainer')?.steps.some(s => /Stacks|Add stack/.test(s.title))).toBe(true);
    expect(targets.find(t => t.id === 'coolify')?.steps.some(s => /Docker Compose/.test(s.title))).toBe(true);
    // Openship is a compose-based panel target too.
    expect(targets.find(t => t.id === 'openship')?.steps.some(s => /Docker Compose|Openship/.test(s.title))).toBe(true);
  });
});

describe('buildDeployScript', () => {
  it('is a POSIX script that drives the user\'s own SSH and never leaks a key or phones home', () => {
    const script = buildDeployScript(buildStack());

    // Shape: a runnable, fail-fast POSIX script using the operator's own ssh/scp.
    expect(script.startsWith('#!/usr/bin/env sh')).toBe(true);
    expect(script).toContain('set -eu');
    expect(script).toContain('scp "$DIR/docker-compose.yml"');
    expect(script).toContain('PROJECT="bms-db-stack"');
    expect(script).toContain('docker compose -p $PROJECT up -d');

    // Key-sovereign by construction: it takes the SSH target from the operator's
    // own argv and NEVER reads, embeds, or transmits a private key.
    expect(script).toContain('TARGET="${1:-}"');
    expect(script).not.toMatch(/PRIVATE KEY|DEPLOY_SSH_KEY|id_rsa|id_ed25519|-i /);

    // No phone-home: the only network egress is ssh/scp to the operator's $TARGET.
    expect(script).not.toMatch(/curl|wget|https?:\/\//);
  });

  it('slugifies stack names into safe compose-project names', () => {
    expect(stackSlug('My Media Server!')).toBe('my-media-server');
    expect(stackSlug('   ')).toBe('stack');
    expect(stackSlug('a__b')).toBe('a-b');
  });
});

describe('buildReadme', () => {
  it('documents the files, quick start, and appends a guide when provided', () => {
    const readme = buildReadme(buildStack(), '## My Guide\n\nDo the thing.');
    expect(readme).toContain('# db stack');
    expect(readme).toContain('docker-compose.yml');
    expect(readme).toContain('.env');
    expect(readme).toContain('docker compose up -d');
    expect(readme).toContain('## My Guide');
  });
});
